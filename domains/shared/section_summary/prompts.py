"""Section Summary 原始 Prompt。

注意：下方 Prompt 为用户提供的原文，必须一字不改。
仅通过 ``build_prompt()`` 替换 ``{{transcript}}`` 占位符。
"""
from __future__ import annotations

PROMPT_PLACEHOLDER = "{{transcript}}"

SECTION_SUMMARY_PROMPT = """你是会议段落速览助手。你的任务是：把一场带时间戳的会议逐字稿切分为若干独立讨论单元，并为每个单元生成结构化速览。只依据原文，不补充原文没有的信息，不做推测。

## 输入
[逐字稿]（每行格式：时间戳 [发言人] 内容）
{{transcript}}

## 一、切分规则（命中任一即切，优先级从高到低）
R1 议程切换：出现"下一个议题""下面请""接下来我们"等明确议程转换信号；或汇报人切换且讨论对象随之改变。
R2 话题切换：讨论对象发生变化（例如从"预算"转到"排期"），即使同一发言人连续讲述，也在此处切分。
R3 决策落点：出现明确结论、拍板、待办指派时，在该句之后切分，使结论与后续讨论分离。
R4 不切：
  - 寒暄、点名、设备调试、流程性过渡（如"能听到吗""稍等"）不单独成段，并入相邻单元。
  - 普通参会人交替发言但话题未变，不因发言人切换而切分。
  - 跑题闲聊、重复表态若无独立信息，并入相邻单元。
R5 边界不明确时：倾向于"并入相邻单元"，而不是制造碎段；但不得因此把两个不同议题合并。

## 二、粒度约束（以语义完整性为准，时间仅作兜底）
- 最小单元：一次完整的发言即可单独成段，不因"轮数少"而强行合并。
- 切分以语义完整性为准：一个单元应能被一句话概括其议题，且议题内部不跳转。
- 时间兜底（用于防止巨段，不用于强制切分）：
  - 单元通常不超过约 10 分钟；若同一议题连续讨论超过 10 分钟且中途出现子议题或阶段结论，则在子议题/结论处再拆。
  - 极短片段（如单句应答"好的""收到"）若无独立信息，并入相邻单元。
- 质量优先级：漏掉实质内容 > 段落过粗 > 段落过碎。宁可段落稍粗，也不得遗漏实质讨论；但不得把一个单元切成多个无法独立概括的碎段。

## 三、逐段生成速览
对切分出的每个单元，生成以下字段：
- time_start：该段第一句发言的时间戳，从原文逐字抄录，不得改写或估算。
- title：概括本段核心议题，不超过 20 字；优先沿用原文议程/议题措辞；不得使用"讨论了一些问题""相关工作"这类空泛表述。
- key_words：提炼本段最关键的 2–4 个关键词，每个不超过 10 个字；必须是名词或名词性短语，无实质内容则空数组。
- section_summary：200 字以内，写清本段讨论的主题和达成的结果。
  有结论就写结论，并带上责任人、待办、关键数字；没有结论就写讨论到哪一步、卡在哪里。
  所有数字、人名、结论必须出自原文，不得推测或补全。

## 四、段落边界定义
- 每个 section 的内容范围：从该段 time_start 所在行开始，到下一段 time_start 所在行的前一行结束。
- 最后一段：从其上 time_start 所在行开始，到逐字稿末尾结束。
- 相邻段不得重叠、不得遗漏行。

## 五、输出格式（严格 JSON 数组，无其他文字）
[
  {
    "time_start": "该段第一句发言的时间戳，如 00:12:30",
    "title": "不超过20字的段落总结标题",
    "key_words": ["关键词，最多四个，每个不超过10个字，没有则空数组"],
    "section_summary": "200字以内，写清本段主题与结果"
  }
]

## 六、硬约束
- 只输出 JSON 数组，不要 Markdown 代码块标记，不要任何解释性文字。
- time_start 必须是原文中真实出现的时间戳，逐字抄录；多个 time_start 必须严格递增，不得重复。
- title 不超过 20 字；key_words 最多 4 个、每个不超过 10 字；section_summary 不超过 200 字。
- key_words 必须是名词性关键词，不得写成句子或动宾短语。
- 不得遗漏原文中的实质讨论内容；不得把多个不同议题合并进一个 section；不得切出无法独立概括的碎段。
- 段落按时间顺序排列，不得跳段或重排。"""


def build_prompt(formatted_transcript: str) -> str:
    """把格式化后的逐字稿填进原始 Prompt 的占位符。"""
    return SECTION_SUMMARY_PROMPT.replace(
        PROMPT_PLACEHOLDER,
        formatted_transcript,
        1,
    )


__all__ = [
    "PROMPT_PLACEHOLDER",
    "SECTION_SUMMARY_PROMPT",
    "build_prompt",
]
