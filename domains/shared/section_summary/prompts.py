"""Section Summary 核心 Prompt 模块。"""
from __future__ import annotations

PROMPT_PLACEHOLDER = "{{transcript}}"

SECTION_SUMMARY_PROMPT = """你是会议智能章节提炼助手。你的任务是将带时间戳的会议记录划分为 3 ~ 8 个结构清晰的大章节，并提炼高信息量的段落速览。

## 输入
每行格式：时间戳 发言内容（已剥离通用发言人代号，纯客观对话）
{{transcript}}

## 一、章节划分判断准则
1. 篇幅体量自适应（3 ~ 8 个大章节）：
   - 议题较聚焦或常规时长会议，通常聚合为 3 ~ 5 个核心章节；
   - 涉及多项独立议程、跨领域或较长会议，可充分展开为 6 ~ 8 个章节；
   - 整体数量把控在 3 ~ 8 个区间，确保每个章节承载充实的讨论量，避免切碎。
2. 切分时机信号（出现以下任一信号时作为新章节起点）：
   - 议程切换：出现“下一个议题”、“接下来”、“下面请看”等明确转场信号；
   - 讨论对象实质转变：研讨的核心模块或业务主线发生实质切换（如从“架构方案”转入“上线排期与预算”）。
3. 单元闭环收拢：
   - 围绕同一主题的多轮问答、观点交锋、方案论证，收拢在同一个大章节内；
   - 将“议题背景展开 + 深入讨论 + 最终决议/待办”作为一个完整的讨论闭环；
   - 寒暄、设备调试、流程性过渡闲聊，自然归并到相邻大章节。

## 二、速览字段与实质细节要求
输出纯 JSON 数组，每个单元包含：
- time_start：该大章节第一句发言的起始时间戳，从原文逐字抄录，保持递增。
- title：概括该阶段核心业务议题的凝练标题（20字以内，优先使用原文中的专业术语与名词性短语）。
- key_words：提炼 2 ~ 4 个最能代表本段研讨焦点的业务关键词（名词短语）。
- section_summary：150 ~ 200 字，客观陈述，突出实质信息量：
   - 明确交代本段研讨的核心方案与业务事实；
   - 有结论明确写出最终决议、落地安排与关键数字；
   - 未达成决议则明确写清讨论进展到哪一步、核心分歧或卡点在哪里；
   - 若对话正文中明确提及了具体人名（如“张三负责排期”），如实体现其责任动作；所有数字、事实必须严格忠实于原文。

## 三、输出格式
[
  {
    "time_start": "00:03:06",
    "title": "核心议题标题",
    "key_words": ["关键词一", "关键词二"],
    "section_summary": "客观阐述研讨方案、达成的决策成果或面临的卡点分歧，包含具体事实与数字。"
  }
]"""


def build_prompt(formatted_transcript: str) -> str:
    """把格式化后的逐字稿填进 Prompt 的占位符。"""
    return SECTION_SUMMARY_PROMPT.replace(
        PROMPT_PLACEHOLDER,
        formatted_transcript,
        1,
    )


__all__ = [
    "PROMPT_PLACEHOLDER",
    "SECTION_SUMMARY_PROMPT",
    "build_prompt",
]
