# ── 英文议程标题本地化 ────────────────────────────────────────────────────────
_AGENDA_EN_HEADING_REPLACEMENTS = (
    ("### 一.", "### I."),
    ("### 二.", "### II."),
    ("中文数字序号", "罗马数字序号"),
)


def localize_agenda_headings_for_en(text: str) -> str:
    """英文议程模式下把中文标题序号本地化为罗马数字。"""
    for old, new in _AGENDA_EN_HEADING_REPLACEMENTS:
        text = text.replace(old, new)
    return text


