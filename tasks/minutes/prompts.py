"""纪要任务 Prompt 体系：支持普通纪要与议题纪要（栏目主序 / 议题主序）三大直出场景。
原生支持中英双语（{lang_name} 角色首尾双锚定与议程序号动态适配）。

核心架构设计：
1. BASE_MINUTES_RULES: 单一事实源 (SSOT)，统领事实提炼原则、正文排版规则与模板遵循输出契约；
2. ROLE_NORMAL / ROLE_AGENDA: 角色定义头；
3. TOPIC_INCREMENT / COLUMN_INCREMENT: 前置架构约定插槽，加粗强化议题对齐与隔离规则；
4. 消除任何硬编码具体子栏名（如 ### 要点梳理），完全通用适配任意业务场景模板。
"""
from __future__ import annotations

# ── 1. 通用规则底座 (SSOT) ──────────────────────────────────────────────────
BASE_MINUTES_RULES = """## 一、 事实提炼原则

1. 忠实原文：严格以转写实录或打标实录为事实依据，只提炼实际内容；不臆测、不编造、不引入外部未讨论信息。
2. 数据与专名准确：专业术语、系统名称、具体数值（金额、比例、指标）及排期完整保留；对比数据完整呈现，不模糊概括。
3. 区分过程与结论：
   - 研讨方案：完整陈述讨论背景、技术思路与论据细节；
   - 拍板决议：仅收录现场明确拍板或达成共识的定调事项，探讨建议不作决议；决议条目首句直接陈述定调结论，依据与背景置于其后或缩进展开，不得先铺陈过程再给结论；
   - 落地待办：必须同时具备责任人、任务动作与截止时间，无明确责任人不列入待办。
4. 客观简练与长句拆短：
   - 长句拆短：单句控制在 100 字内，按事实脉络拆分，避免多层因果与复杂从句堆叠；
   - 过滤冗余：剔除寒暄、口头禅、重复发言与主持转场词；判定标准为“删去后是否损失事实、判断或因果”，凡承载具体事实、数据、例子或关键判断的表述一律保留，不得以“进行了讨论”“交换了意见”等概括替代具体内容；
   - 原话保留：关键定调、关键判断可保留发言人原话片段（加引号），与第三人称转述交替使用，仅限承载核心判断或分歧焦点的表述，不保留寒暄与语气词。
5. 空内容处理：某栏目或子项无实际研讨内容时直接省略，不输出“无”“未提及”等占位说明。

## 二、 正文排版规则

1. 结构与分条：
   - 除概览单段（200 字内）外，正文严禁大段叙述；不同事项、举措或维度分行独立成条，不合并表述；
   - 篇幅按重要性分配，不追求各条目字数均衡；重点方向、核心成果可展开，次要信息一句带过；
   - 单条列表项承载的并列事实不超过 3 项；并列项超过 3 条，或单条含 3 项以上并列细节时，主干行只给定调，其余平铺或缩进展开，不得逐条重复加粗标题。

2. 列表层级与行形态：
   - 行形态按内容性质择用，不强求同构：
     - 加粗事项行：`- **事项名**：具体事实陈述`，用于重点事项；
     - 普通陈述行：`- 事项名：具体事实陈述` 或 `- 具体事实陈述`，领起短语不加粗，用于直接承接细节、并列事实；
   - 缩进展开（`  - `）：含多项并列举措、对比数据或分支细节时，主干行单列定调，下方缩进两空格分点展开，每条独占一行；
   - 避免一行内连续拼接多句复杂复合叙述。

3. 列表项命名与加粗约束：
   - 加粗事项行的加粗项必须为具体业务对象或方案举措，避免抽象泛指序号；
   - 行内加粗仅落在关键判断词、数值、专名上，不整句加粗；
   - 行内加粗优先考虑拍板结论、关键数值（延迟/阈值/比例）、分歧焦点；过程描述、常规动作、背景信息不加粗。

4. 决议、待办与分组：
   - 决议项：去除建议性词汇，直接陈述拍板定调结论与指标要求；
   - 待办项：清晰交代责任主体、具体任务、交付物与时间节点四要素；交付物须可验证（如“输出甘特图”“提交方案文档”），不得仅写“跟进”“推进”“落实”等动作标签；
   - 人员分组：人名不作各级标题，按人归纳时用独立加粗行（`**姓名**：`）；未核实姓名者保留原文角色编号。

5. 原话引用与问答：
   - 关键定调原话自然融入对应事项，不脱离上下文孤立列出；
   - 正式问答随议题就地收录，问答成对呈现，长答复按核心要点提炼。

6. 未决事项收口：
   - 现场讨论但未拍板、未达共识的事项，归入“待确认事项”，逐条列明分歧点与待确认方；
   - 不与决议混列，不表述为结论；无分歧点的纯信息同步不列入。

## 三、 模板遵循与输出契约
1. 标题层级忠实：模板中声明的一级标题（形如 `# 栏目名`）必须 100% 遵从，名称与顺序原样输出，严禁自行增删、改名或调整层级。
2. 指令替换执行：模板中方括号 `[...]` 内的文字为写作指令，输出时方括号及内部文字必须全部剔除，整体替换为从实录中提炼的具体事实。
3. 纯净 Markdown 直出：严禁包裹 markdown 代码块（如 ```json），严禁在正文外输出任何多余寒暄、说明或前言后语，输出的第一个字符必须直接是首个 `#` 标题行。
4. 语言一致性：最终输出语种必须严格是【{lang_name}】。"""


