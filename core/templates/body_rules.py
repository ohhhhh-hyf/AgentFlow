"""正文形态与信息量规则（单点维护，多条渲染路径共用同一份文本）。"""
from __future__ import annotations

BODY_FORMAT_RULES = """- **结构与层级（树状展开）**：并列同类事项按业务或大类组织；组内主干条目一行一项（支持 `1. ` 或 `- `），下挂缩进子条 `  - ` 展开核心参数与依据；标签嵌在行首（`- **标签**：内容`），各小节之下分条列出。
- **大类分组与自适应隐去**：明细条目较多时按模块建立小节或组名；「人」不是板块：按人分组时用独占一行的 `**姓名**：`（本人那一组写 `**与我相关**：`），不得把人名或「与我相关」写成 `##` 标题；事实驱动建组：有事实才建组立项，无事实时组名整行直接不出现；若整栏或整组无相关事实且模板允许省略，该栏或该组自适应隐去，不输出「未提及」、「本栏隐去」等冗余占位词。
- **受控二级缩进（显式场景触发）**：当事项包含 ≥2 个并列维度时，统一使用二级无序缩进（2 空格 `  - `）展开：① 现状/问题 与 解决方案 并存时（主条定方向与结论，下挂 `  - ` 分别展开成因与应对措施）；② 赞成观点/优势 与 潜在顾虑/风险 并存时（主条定共识倾向，下挂 `  - ` 分别展开支持依据与保留意见/顾虑）；③ 核心交付物 包含多个并列指标/模块/时限时（主条定总目标，下挂 `  - ` 分别展开分项参数、验收指标与责任节点）。
- **篇幅与字数上限**：一般叙述单段紧凑控制在约 150–220 字（不超过约 300 字）；条目一事一条，日常单条紧凑控制在约 45–80 字（单条不超过约 150 字，长复杂事实使用二级无序缩进 `  - ` 展开）；概况/背景类单段控制在 200–280 字（单段不超过 400 字、单段写完）。
- **行动项与任务表达**：待办事项采用自然陈述句（`- **事项名**：交代具体做什么、由谁负责、何时完成及交付目标`），责任人与时间节点自然融入句中，未交代项直接省略；复杂事项下挂缩进子条 `  - ` 展开细节；状态标记（已完成 / 进行中 / 未开始 / 阻塞 / ⏸未开始）仅在模板要求时出现一次。
- **事实锚定与引用从属**：给出结论时正面交代对应的事实与依据，结论与支撑事实紧密锚定；引述关键原话（`>`）必须作为列表条目或段落内部的论据支撑依附存在，不输出悬空孤立引用块；表格栏按模板约定完整保留表头与数据行。
- **问答与对话规范**：问答栏只收真问答（一方求信息、对方回应且相邻，排除设问与串场）；问答/对话的一轮为一个记录单元，问答各占一段，单段连贯，再长也不拆段，长答话按要点压缩在约 300 字以内；问答/对话的称呼行按模板要求每轮加粗；无正式问答且模板允许省略时整栏自适应隐去。
- **称呼规范与语音识别纠错**：成员称呼按 姓名 > 原文明确角色 > 原始编号 回退，已知姓名时规范使用全场统一真实姓名；上下文能明确辨识的语音识别错按公认规范修正，无法确定的忠实照原文，严禁凭空猜测造名。"""

