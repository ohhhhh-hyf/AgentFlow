"""正文形态与信息量规则（单点维护，多条渲染路径共用同一份文本）。"""
from __future__ import annotations

BODY_FORMAT_RULES = """- **结构与层级**：并列事项按业务或大类分组；有三级/四级小节时，正文用 `- ` 列表陈述方案、事实与数据；无小节时用 `- **事项名**：内容`；组内主干条目一行一项，单条包含多个维度时用 2 空格 `  - ` 展开；每条交代一个完整事项，禁止只有结论的孤条，同一句话不拆成多条。
- **分组与隐去**：人名不作标题；按人分组用独占一行 `**姓名**：`，本人组用 `**与我相关**：`；无事实依据的组不输出；无内容且模板允许省略的栏目整栏连同标题隐去，不写「未提及」「本栏隐去」等说明。
- **篇幅**：模板显式条长/字数要求优先；段落紧凑、一事一议；单段不超过约 300 字，单条不超过约 150 字，概况单段不超过 400 字；服从模板栏位要求和上下文【篇幅预算】，不写字数说明。
- **行动项**：`- **事项名**：做什么 + 谁负责 + 何时完成 + 交付目标`；责任人、时间节点自然融入句中，未交代项省略；状态标记（已完成 / 进行中 / 未开始 / 阻塞）仅在模板要求时出现一次。
- **引用与论据**：原话作为结论的论据依附存在，不单独堆砌；表格按模板约定保留表头和数据行，每条数据独占一行。
- **问答**：只收真问答；问答/对话的一轮为一组，问、答各一段，单段连贯，再长也不拆段；长答话按要点压缩；问答/对话的称呼行按模板要求每轮加粗；无正式问答且模板允许省略时整栏隐去。
- **成员称呼**：姓名 > 原文角色 > 原始编号；能确认的语音识别错误按规范修正；不推断姓名。"""

# 保持向后兼容别名，单点收敛为 BODY_FORMAT_RULES
CORE_LAYOUT_RULES = BODY_FORMAT_RULES

