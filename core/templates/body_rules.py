"""正文形态与信息量规则（单点维护，多条渲染路径共用同一份文本）。"""
from __future__ import annotations

BODY_FORMAT_RULES = """
- **结构与层级**：并列事项按业务或大类分组；有三级/四级小节时正文用 -  列表；无小节时以「- 事项名：」引导：若含分号或多维度则独占一行，单条包含多个维度时用 2 空格 `  - `展开；单维度简短事实冒号后同行呈现；组内主干条目一行一项，每条交代一个完整事项并融入必要的背景、举措与定调；同一句话不拆成多条碎句，但由分号分隔的并列举措或成效须分点独立成项。 
- **分组与空内容**：人名不作标题；按人分组用独占一行 `**姓名**：`，本人组用 `**与我相关**：`；有实质研讨事实的组如实饱满呈现，无事实依据的组不输出；无内容且模板允许省略的栏目（含子栏、分组）不生成标题与正文，不写「未提及」等空值说明。
- **篇幅**：模板显式条长/字数要求优先；概况单段严格控制在 200 字以内，精炼交代背景与定调；正文段落与条目以事实充分展开为准；全场聚焦单一议题时，须按业务维度、推进举措等要点拆分为多个独立小议题，分段/分项成节；
- **行动项**：`- **事项名**：责任人、时间节点与协同要求自然融入句中，具体动作与交付标准交代明确闭环，未交代项省略；状态标记（已完成 / 进行中 / 未开始 / 阻塞）仅在模板要求时出现一次。
- **引用与论据**：关键定调与核心数据应有据可依，重要发言人洞见或原则性原话自然融入，增强说服力与现场质感，不单独堆砌无关闲话；表格按模板约定保留表头和数据行，每条数据独占一行。
- **问答**：只收真问答；问答/对话的一轮为一组，问、答各一段，单段连贯；长答话按要点压缩；问答/对话的称呼行按模板要求每轮加粗；无正式问答且模板允许省略时不生成该栏标题与正文。
- **成员称呼**：姓名 > 原文角色 > 原始编号；能确认的语音识别错误按规范修正；不推断姓名。
"""

