"""模板渲染 prompt 公共构建：占位符模板 / 格式规范模板两类应对。

task 的渲染模板 prompt 只需提供差异项（渲染器名、内容来源、空内容规则、
额外规则），**类型判断与两类渲染规则**统一在这里维护：

- ``build_template_render_prompt``：生成**基础规则**（事实来源、结构忠实、
  事实忠实、语句通顺、篇幅两遍法）——不含类型判断，供三类路径共用
- ``PLACEHOLDER_RULES`` / ``SPEC_RULES``：**类型专用规则**，由
  ``template_router.route_template`` 在判型成功后拼进 system prompt——
  LLM 只执行已判定类型的规则，不再自行判断
- ``FALLBACK_TEMPLATE_RULES``：两类型简述，供判型失败 / 路由关闭时兜底
  （此时类型未知，才需要 LLM 自己判断）

设计原则：规则只写**通用原则**，不绑定任何具体业务（会议 / 访谈 / 待办 /
风险 / 知识点等均适用），不在 prompt 中夹带针对特定测试数据的示例或软引导。
"""
from __future__ import annotations

from core.templates.body_rules import BODY_FORMAT_RULES


def build_template_render_prompt(
    *,
    renderer: str,
    source: str,
    empty_rule: str,
    extra_rules: list[str] | None = None,
    source_rule: str | None = None,
) -> str:
    """按差异项生成模板渲染的基础规则（类型判断由 template_router 完成）。

    ``source_rule`` 可选覆盖第一条"事实来源"规则：默认口径把「{source}」当唯一事实来源、
    只做结构填充；需要"以原文为第一来源、把细节写足"的任务（如会议纪要）自行传入口径。
    """
    rules = [
        source_rule
        or f"唯一事实来源是「{source}」与用户消息中的业务素材；不新增、不改写事实。",
        "严格保留模板的标题层级、栏目顺序与表格结构；"
        "占位符模板的标题文字按占位规则去掉方括号；不新增模板外栏目；"
        "并列栏目分别成节，模板点名的栏目必须覆盖。",
        "有据才写；无依据按模板空值规则处理；"
        "不输出「未提及」「本栏隐去」等说明，不复述模板要求。",
        empty_rule,
        "模板写「简洁 / 粗略」时仍保留主要事实；"
        "数字、日期、人名、责任归属以素材为准；"
        "「预计 / 可能 / 有望」保留预期属性；语句完整通顺。",
        "篇幅优先级：模板栏位上限 > 上下文【篇幅预算】 > 按事实自然展开；"
        "不输出字数说明。",
        "**冲突裁决**：事实保真 > 模板结构 > 表达精炼。",
        "直接输出 Markdown 正文；不解释、不使用代码围栏、不使用 emoji。",
        "同输入复跑保持结构与关键措辞稳定。",
    ]
    if extra_rules:
        rules.extend(extra_rules)
    numbered = "\n".join(f"{i}. {rule}" for i, rule in enumerate(rules, start=1))
    return (
        f"你是{renderer}。根据{source}和下方输出模板，生成输出。\n\n"
        "模板类型已由系统判定并在下方标注，请按对应类型规则执行。\n\n"
        "通用规则：\n"
        f"{numbered}"
    )


PLACEHOLDER_RULES = ("""
【模板类型已判定：占位符模板】模板含 [描述] / [xxx] 占位符

## 结构与占位
1. 只替换方括号内的占位内容；方括号外的固定文字、表头与分隔行原样保留。
   标题行例外：按第 2 条去掉方括号，标题行不得出现 [ ]。
2. 标题占位 `# [栏目标题]`：保留原 # 个数，去掉方括号（如 `## [全文摘要]` → `## 全文摘要`）；标题行只放栏名。
3. 表格占位行 `| … | … |`：删除占位行，按表头生成真实数据行，每条数据独占一行；
   状态或等级按模板/占位说明填写，不自行扩展枚举。
4. 每个占位按说明填写；多选一占位只能取其一；占位说明中的数量/字数约束优先。
5. “如：…”仅示意格式，禁止照抄内容。
6. 无依据且模板允许省略的栏目，整栏连同标题隐去；
   确需占位时按模板指定词填写，不输出说明性占位词。

## 形态（栏内排版）
"""
    + BODY_FORMAT_RULES
)


SPEC_RULES = """
【模板类型已判定：格式规范模板】模板无占位符，而是输出格式说明 + 示例

1. 严格按【格式指令】的字段、顺序、标题、条数输出；示例仅示意格式，禁止照抄内容。
2. 指令要求 N 句 / N 行 / N 条时，输出恰好 N 个完整单元。
3. 指令中用顿号或「与/和/及」并列的写作任务，分别覆盖。
4. 每项内容都要有原文依据；简洁仍须保留主要事实，先重要后次要。
5. 只有指令声明字数/条数上限时才按上限控制；未声明服从【篇幅预算】。
6. 不输出规则解释、字数说明或额外前言。
"""


FALLBACK_TEMPLATE_RULES = """
先判断模板类型：
- 含 [xxx] → 按占位符规则填充；
- 格式说明 + 示例 → 按指令结构输出，示例仅示意格式。

共性：保留模板结构、事实保真、无依据空栏隐去、不照抄示例、不输出元说明。
"""
