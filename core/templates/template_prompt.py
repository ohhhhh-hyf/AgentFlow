"""模板渲染 prompt 公共构建：占位符模板 / 格式规范模板两类应对。

task 的渲染模板 prompt 只需提供差异项（渲染器名、内容来源、空内容规则、
额外规则），**类型判断与两类渲染规则**统一在这里维护：

- ``build_template_render_prompt``：生成**基础规则**（事实来源、结构忠实、
  事实忠实、语句通顺、篇幅两遍法）——不含类型判断，供三类路径共用
- ``PLACEHOLDER_RULES`` / ``SPEC_RULES``：**类型专用规则**，由
  ``template_router.route_template`` 在判型成功后拼进 system prompt——
  LLM 只执行已判定类型的规则，不再自行判断
- ``FALLBACK_TEMPLATE_RULES``：两类型简述，供判型失败 / 路由关闭时兜底
  （此时类型未知，才需要 LLM 自己判断）

设计原则：规则只写**通用原则**，不绑定任何具体业务（会议 / 访谈 / 待办 /
风险 / 知识点等均适用），不在 prompt 中夹带针对特定测试数据的示例或软引导。
"""
from __future__ import annotations

from core.templates.body_rules import BODY_FORMAT_RULES


def build_template_render_prompt(
    *,
    renderer: str,
    source: str,
    empty_rule: str,
    extra_rules: list[str] | None = None,
    source_rule: str | None = None,
) -> str:
    """按差异项生成模板渲染的基础规则（类型判断由 template_router 完成）。

    ``source_rule`` 可选覆盖第一条"事实来源"规则：默认口径把「{source}」当唯一事实来源、
    只做结构填充；需要"以原文为第一来源、把细节写足"的任务（如会议纪要）自行传入口径。
    """
    rules = [
        source_rule
        or f"唯一事实来源是「{source}」与用户消息中的原文：只做结构填充与措辞整理，不新增事实",
        empty_rule,
        "直接输出最终稿 Markdown 正文，不添加解释、JSON 或外层代码围栏（``` 或 ```text / ```markdown）",
        "同输入复跑时，结构与关键措辞保持稳定",
        # 结构忠实：标题可见
        "严格保留模板的固定标题、表头、分隔行与栏目划分；只填写可变部分，不改动固定文字",
        "模板点名的每个栏目都必须以可见的小节标题出现，"
        "正文写在标题下方；各栏正文完整依附其小节标题，避免无栏目标题直接堆叠。"
        "【动态条件栏目例外】：若模板说明明确标明某栏为条件呈现栏目（如无现场问答、无风险卡点时整体不呈现），"
        "且会议素材确实未发生该环节，则该栏目连同其 ## 标题行整体完全不输出；"
        "严禁输出「只有标题、没有正文」的光杆标题，更严禁将「本栏隐去」、「整栏省略」、「未提及」等提示词原话作为正文输出",
        "表格：表头 + 分隔行 + 数据行各占一行，每条数据独占一行",
        # 并列拆分
        "模板或用户描述里用顿号、「与/和/及」并列的栏目名，视为彼此独立的写作任务："
        "各栏分别成节填写（各自标题 + 正文），各节独立展开",
        # 栏目有据才写 / 信息量
        "模板点名的每个栏目都要覆盖：从原文与内容来源中提炼与该栏主题相关的信息；"
        "仅当来源对该栏主题完全没有可写信息时，才按空内容规则处理。"
        "严格依据提供的素材内容提炼，不使用外部常识、百科履历或未出现的环节补全",
        "模板写「简洁 / 粗略 / 概要 / 无需深入」时：省略展开论证与次要枝节，"
        "但每栏仍须写清原文中与该栏相关的主要事实与要点（可多句），"
        "保证各栏关键信息与事实脉络完整交代，避免空泛概括",
        # 事实忠实
        "有据才写：每一句都要能在原文或内容来源中找到依据；拿不准就不写，或按空内容规则处理",
        "谁做了什么、谁说了什么，以原文主语与责任人为准；数字、日期、比例、金额优先沿用原文表述",
        "「预计 / 可能 / 有望」等谨慎语气忠实保留其预期属性，不写成已发生事实",
        # 语句通顺
        "语句须完整通顺：主谓齐全，无缺字漏字、无重复赘字、无生硬拼接、无半截句；"
        "指代清楚，并列成分用顿号或逗号理顺",
        # 篇幅：模板栏位上限优先，其次使用上下文中程序计算的动态预算
        "仅当模板或指令声明了字数/行数上限时，才按上限控制篇幅"
        "（「约N字」按 N±10%；区间按区间；**不可超上限**）。"
        "有上限时从最重要信息写起，次要过程可省略，保证语句完整交代。"
        "**未声明栏位上限时，服从上下文【篇幅预算】**；没有动态预算时再按事实量自然展开，不按原文比例机械扩写。"
        "各栏把与该栏相关的事实、数字、责任人、时限写清；推行高信息密度公文体，去套话、长句主动拆短，精简压缩只删修辞铺垫与重复表达，不删除客观事实",
        # 冲突裁决：模板栏位限制 > 动态总预算；预算内保真 > 结构 > 压表达。
        "**冲突裁决**：**保真优先**（不删事实、不改口径与人名数字）→ 其次保结构（栏目齐全）→ 最后才压表达；"
        "超出有效预算时先删套话与同义反复、再按主题归组但保留组内子项——**压缩不等于删事实**："
        "数字、日期、人名、决策、承诺、模块进展与风险一律保留",
        "输出专注交付正文，不出现字数元说明（如「约250字」「全文合计约200-300字」「字数要求」等）；字数只作内部控制",
    ]
    if extra_rules:
        rules.extend(extra_rules)
    numbered = "\n".join(f"{i}. {rule}" for i, rule in enumerate(rules, start=1))
    return (
        f"你是{renderer}。根据{source}和下方输出模板，生成输出。\n\n"
        "模板类型已由系统判定并在下方标注，请按对应类型规则执行。\n\n"
        "通用规则：\n"
        f"{numbered}"
    )


PLACEHOLDER_RULES = ("""
【模板类型已判定：占位符模板】模板含 [描述] / [xxx] 占位符

## 结构与占位
- 保留模板的固定标题、表头、对齐分隔行与栏目划分；**只替换**方括号内的占位
- 固定 `## 栏目标题` 必须原样出现在输出中；占位处只填该栏正文，不要把正文写进标题行（例外：若该栏为模板明确注明的条件呈现栏目且无相关事实，整栏连同 ## 标题完全不输出，严禁输出光杆标题）
- **标题占位**（形如 `# [栏目标题]` 的标题行）：方括号内文字就是该栏标题——
  输出时**保留原来的 # 个数**（`# [项目概况]` → `# 项目概况`，不要改成 `##`），
  标题行**只放栏名**；该栏正文写在标题下方的正文占位处，正文与标题分行放置
- **表格占位数据行**（表格中整行都是 `…` 的行）：这是待填数据行的占位，不是固定文案——
  输出时**删除该占位行**，按表头列序生成为真实数据行（1..N 行、各占一行），
  每格内容按本栏占位说明与原文提炼（如等级列填 🟢正常/🟡低风险/🔴高风险 或 高/中/低）；
  生成真实数据行，不保留 `| … | … |` 占位行
- 占位说明中若出现「如：…」等字样，仅为写法示范，**禁止照抄**其中的具体内容
- 每个占位都要填写：有依据则写与该栏主题对应的具体内容；若占位说明允许不呈现或省略，无依据直接留空交由程序自适应修剪；需占位时写该栏约定的缺省词（占位说明/模板优先，未约定时写「未提及」）
- 正文与字段值专注呈现业务事实，不复述或解释模板要求，缺内容按约定空值处理，严禁将「本栏隐去」、「整栏省略」等提示词说明输出到正文中
- 占位说明提到数量 / 字数时按该约束填写，但不要把字数说明本身写进输出；多选一占位（[a / b / c]）只能取其一

## 形态（栏内排版）
"""
    + BODY_FORMAT_RULES
)


SPEC_RULES = """
【模板类型已判定：格式规范模板】模板无占位符，而是输出格式说明 + 示例

## 格式
- 严格按【格式指令】规定的字段结构与格式输出；【示例】仅演示格式，**禁止照抄**示例中的输入内容
- 指令要求分节/分条时，输出必须带齐对应标题或条目标记，保持清晰结构
- 模板声明「用 N 句话 / N 行 / N 条」等数量时，输出恰好 N 个完整单元；每句须完整通顺
- 指令中用顿号或「与/和/及」并列的写作任务，输出中须分别覆盖

## 内容
- 每项内容都要有原文依据；无依据按指令约定的空值形式处理
- 「简洁/粗略」时仍须覆盖主要事实，避免空泛一句带过
- 表格保留表头与栏目；数字、日期、归属以原文为准；「预计 / 可能 / 有望」忠实体现预期属性
- 语句完整通顺

## 篇幅
- **仅当指令声明了字数/条数上限时**才按上限控制（「约N字」按 N±10%；区间按区间；不可超上限）
- 有上限时从最重要信息写起，次要过程可省略，确保陈述完整闭环
- **未声明栏位上限时，服从上下文【篇幅预算】**；没有动态预算时按事实量自然展开，不按原文比例机械扩写；压缩只删套话、铺垫与重复表达，不丢原文事实
- 输出专注交付内容，不出现字数元说明或对模板规则本身的说明
"""


FALLBACK_TEMPLATE_RULES = """
先判断模板类型再填写：
【占位符模板】模板含 [xxx] → 保留固定标题与表结构，只替换占位；「如：」示例仅为写法示范
【格式规范模板】模板是格式说明 + 示例 → 按指令结构输出；示例仅演示格式

共性：
- 栏目标题可见，正文在标题下，避免无标题直接堆内容
- 顿号/「与和及」并列栏目分别成节
- 简洁而充实：每栏写清主要事实
- 语句通顺；篇幅两遍法；输出不包含「约N字」等元说明；数字/日期/归属忠实原文
"""
