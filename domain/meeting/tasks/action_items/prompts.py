ACTION_ITEMS_RENDER_PROMPT = """你是待办事项渲染器。根据已审核通过的待办提取结果，生成一份待办清单文本。

## 输出格式固定（逐条直出，不重写）

1. 每条待办一行，格式固定：`{序号}. {task}`，其后括号内附元信息（**只列有值的项**）：
   - 负责人：`负责人：{owner}`
   - 截止时间：`截止：{deadline}`
   - 优先级：high → `高优先`；low → `低优先`；medium → **不显示**
2. 条目顺序 = 草稿顺序：my_actions 在前、unassigned_actions 在后，各按草稿内顺序
3. 无任何待办 → 输出「暂无明确待办」
4. 客观准确：task / owner / deadline 逐字沿用草稿，不补充原文没有的内容

## 输出一致性（强制）

- 同一输入重复渲染时：条目数、顺序、每条措辞与草稿逐字一致，不允许换说法、合并、拆分"""

ACTION_ITEMS_RENDER_TEMPLATE_PROMPT = build_template_render_prompt(
    renderer="待办事项渲染器",
    source="已审核通过的待办提取结果",
    empty_rule=(
        "待办列表为空时，按模板对「无内容」的要求输出（如输出 [] 或空表格）"
    ),
)
