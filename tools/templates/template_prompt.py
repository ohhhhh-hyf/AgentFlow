"""模板渲染 prompt 公共构建：占位符模板 / 格式规范模板两类应对。

task 的渲染模板 prompt 只需提供差异项（渲染器名、内容来源、空内容规则、
额外规则），**类型判断与两类渲染规则**统一在这里维护：

- ``build_template_render_prompt``：生成**基础规则**（事实来源、结构忠实、
  事实忠实、语句通顺、篇幅两遍法）——不含类型判断，供三类路径共用
- ``PLACEHOLDER_RULES`` / ``SPEC_RULES``：**类型专用规则**，由
  ``template_router.route_template`` 在判型成功后拼进 system prompt——
  LLM 只执行已判定类型的规则，不再自行判断
- ``FALLBACK_TEMPLATE_RULES``：两类型简述，供判型失败 / 路由关闭时兜底
  （此时类型未知，才需要 LLM 自己判断）

设计原则：规则只写**通用原则**，不绑定任何具体业务（会议 / 访谈 / 待办 /
风险 / 知识点等均适用），不在 prompt 中夹带针对特定测试数据的示例或软引导。
"""
from __future__ import annotations


def build_template_render_prompt(
    *,
    renderer: str,
    source: str,
    empty_rule: str,
    extra_rules: list[str] | None = None,
) -> str:
    """按差异项生成模板渲染的基础规则（类型判断由 template_router 完成）。"""
    rules = [
        f"唯一事实来源是「{source}」与用户消息中的原文：只做结构填充与措辞整理，不新增事实",
        empty_rule,
        "只输出最终稿正文；不要解释、不要 JSON；"
        "禁止用 Markdown 代码围栏（``` 或 ```text / ```markdown）包裹整段输出",
        "同输入复跑时，结构与关键措辞保持稳定",
        # 结构忠实：标题可见
        "严格保留模板的固定标题、表头、分隔行与栏目划分；只填写可变部分，不改动固定文字",
        "模板点名的每个栏目都必须以可见的小节标题出现（如 ## 栏目标题），"
        "正文写在标题下方；禁止把某一栏正文顶到一级标题、导致「没有栏目标题、只有一段话」",
        "表格：表头 + 分隔行 + 数据行各占一行，禁止把多条数据挤在同一行",
        # 并列拆分
        "模板或用户描述里用顿号、「与/和/及」并列的栏目名，视为彼此独立的写作任务："
        "各栏分别成节填写（各自标题 + 正文），禁止揉进同一标题或同一段",
        # 栏目有据才写 / 信息量
        "模板点名的每个栏目都要覆盖：从原文与内容来源中提炼与该栏主题相关的信息；"
        "仅当来源对该栏主题完全没有可写信息时，才按空内容规则处理。"
        "禁止用外部常识、百科履历或未出现的环节补全",
        "模板写「简洁 / 粗略 / 概要 / 无需深入」时：省略展开论证与次要枝节，"
        "但每栏仍须写清原文中与该栏相关的主要事实与要点（可多句），"
        "禁止每栏只剩一句空泛概括而丢掉可写的关键信息",
        # 事实忠实
        "有据才写：每一句都要能在原文或内容来源中找到依据；拿不准就不写，或按空内容规则处理",
        "谁做了什么、谁说了什么，以原文主语与责任人为准；数字、日期、比例、金额优先沿用原文表述",
        "「预计 / 可能 / 有望」等谨慎语气不得写成已发生",
        # 语句通顺
        "语句须完整通顺：主谓齐全，无缺字漏字、无重复赘字、无生硬拼接、无半截句；"
        "指代清楚，并列成分用顿号或逗号理顺",
        # 篇幅：字数/行数是硬上限，直接按上限生成，宁短勿长
        "模板或指令声明的字数/行数是**硬上限**（如「约300字」「200-300字」「约3行」）："
        "声明「约N字」按 N±10% 执行；声明区间严格按区间执行。"
        "**直接按上限生成，不要先写全再压缩**：从最重要信息写起，"
        "优先写原文结论、关键数字、责任人、时限、模板点名栏目；"
        "次要内容（过程铺陈、检查经过、客套话、展开论证、示例）**主动省略**，写不下就不写。"
        "宁可偏短（短 10-20% 可接受），**不可超上限**（超 10% 即不合格，必须删减到上限内再交付）；"
        "明显不足（低于区间下限）时，补充原文关键结论、数字、责任人、时限。"
        "禁止截断半句导致语病",
        "正文中**严禁**出现字数元说明（如「约250字」「全文合计约200-300字」"
        "「字数要求」等）；字数只作内部控制，不要写进输出",
    ]
    if extra_rules:
        rules.extend(extra_rules)
    numbered = "\n".join(f"{i}. {rule}" for i, rule in enumerate(rules, start=1))
    return (
        f"你是{renderer}。根据{source}和下方输出模板，生成输出。\n\n"
        "模板类型已由系统判定并在下方标注，请按对应类型规则执行。\n\n"
        "通用规则：\n"
        f"{numbered}"
    )


PLACEHOLDER_RULES = """
【模板类型已判定：占位符模板】模板含 [描述] / [xxx] 占位符

## 结构
- 保留模板的固定标题、表头、对齐分隔行与栏目划分；**只替换**方括号内的占位
- 固定 `## 栏目标题` 必须原样出现在输出中；占位处只填该栏正文，不要把正文写进标题行
- **标题占位**（形如 `# [栏目标题]` 的标题行）：方括号内文字就是该栏标题——
  输出对应层级的标题行（如 `## 栏目标题`），标题行**只放标题文字**；
  该栏正文写在标题下方的正文占位处，禁止把正文塞进标题行，也禁止丢掉该栏标题
- **表格占位数据行**（表格中整行都是 `…` 的行）：这是待填数据行的占位，不是固定文案——
  输出时**删除该占位行**，按表头列序生成为真实数据行（1..N 行、各占一行），
  每格内容按本栏占位说明与原文提炼（如等级列填 🟢正常/🟡低风险/🔴高风险 或 高/中/低）；
  **禁止**把 `| … | … |` 占位行原样照抄进输出
- 表格：表头 + 分隔行 + 数据行（各占一行）；数据行按内容生成多行，禁止同行粘连
- 占位说明中若出现「如：…」等字样，仅为写法示范，**禁止照抄**其中的具体内容
- 若固定标题本身用「与/和/及」把两个主题绑在一起，正文内仍须分段写清两侧主题

## 占位填充
- 每个占位都要填写：有原文依据则写与该栏主题对应的具体内容；无依据按占位说明的默认写法（如「未提及」/「未明确」）
- 占位/栏目标题点名某主题时，从原文提炼该主题信息，不要因「原文没有同名小标题」就空写
- 「简洁/粗略」≠ 空洞：每栏写清主要事实与要点，可多句
- 占位说明提到数量 / 字数时按该约束填写，但**不要**把字数说明本身写进字段值
- 多选一占位（[a / b / c]）只能取其一

## 语句与事实
- 每栏写成完整通顺的句子；禁止半截句、语病拼接；字段值不要重复栏目标题作前缀
- 有据才写；「预计 / 可能 / 有望」保持谨慎语气
- 身份/称谓只写原文出现的信息，不补外部履历或评价

## 篇幅（硬上限，直接按上限生成）
- 字数/行数是**硬上限**：声明「约N字」按 N±10% 执行；区间严格按区间执行
- **直接按上限生成，不要先写全再压缩**：从最重要信息写起，优先写结论、关键数字、责任人、时限
- 次要内容（过程铺陈、检查经过、客套话、展开论证、示例）**主动省略**，写不下就不写
- 宁可偏短（短 10-20% 可接受），**不可超上限**；明显不足时补原文关键结论、数字、责任人、时限
- 禁止截断半句；正文中不要写「约N字」等元说明
"""


