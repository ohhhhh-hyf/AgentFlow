from __future__ import annotations

BODY_FORMAT_RULES = """- **分点优先**：并列同类事项（多主体、多事项、多步骤、多分项数据、清单类要点）**必须** `- ` 一条一行、标签嵌在行首（`- **标签**：内容`），不要把多条压进一句；**同一栏连续 3 行以上独占一行的 `**标签**：`（没有 `- `）算形态缺陷**——清单必须分点；`## 名称` 小节之下**必须** `- ` 一条一行（知识、课堂、清单类尤其如此），不得写成连续段落
- **大类分组**：独占一行的 `**大类**：` 只用来把该栏分成 **2–5 个大类**，大类之下必须跟 `- ` 子条；**一条下有 ≥2 个并列子事项时必须用缩进子条 `  - ` 拆开，不得塞进同一句**
- **禁止同名重复**：`## X` 小标题之下第一条**不得**再写 `**X**：`（标题已经说了）；`# 栏名` 之下不得把栏名当标签再复述一遍；**同一栏同一个 `**标签**：` 最多出现 1 次**（同类多条用「一个标签 + 缩进子条 `  - `」聚合，不要重复标签凑数）
- **段落上限**：一般叙述单段不超过 **3 句或约 200 字**，超过就拆段或改成 `- ` 分点；**概况/一段话概括类单段不超过 400 字、最多 3 段**（该栏自己声明了尺寸的以声明为准）
- **每条写实**：**每条 = 一个事项的完整交代**——主体（谁/哪个部门提出或负责）+ 具体做法或判断依据 + 针对什么问题（承接现象/根因）+ 程度/数字/时限 + 影响或下一步；**原文提供了哪些要素就写进同一条**（且必须带**至少两项要素**），不得只留一个动作或一句结论；**每条 30–120 字**，只写「状态 + 名词」或半句碎片不算合格；**超过 120 字必须拆**（多条或缩进子条 `  - `），不得把并列子事项、多段细节塞进同一条
- **禁止结论式孤条**：只写「账号未变现」「成本控制差」这类结论不算合格——要交代它对应的事实（什么现象、依据的数字、谁的说法）；原文确实只有方向性表述（如「明年开会再讨论」）时照实写，但要写明它针对什么问题，不得退化成口号
- **条数宁多不漏**：原文有几项就写几条（不要合并同类项）；一条只放一件事或一个判断，需要细分时用缩进子条 `  - `
- **同一句话不拆多条**：同一议题的碎片（同一次修改的几个小动作、同一事项的并列子项）合并成一条写清，不要一句一条——「修改了参数」「任务已调整」这类同义半句不单独成条
- **状态标记（✅已完成 / 🔄进行中 / ⛔阻塞）**只在模板要求时使用，且只出现在**表格的状态列或任务名后一次**；条目正文不要逐条重复「进行中」，状态之外必须写清进展内容
- **表格栏**：某栏明细由下表承载（说明里写「按下表…」「只用下表」）时，正文写**一句总述**（共 N 项 / 完成 X 项 / 总体判断）；**有表就不许写「未提及」「未明确」**（有表即有内容），也不要复述表格内容
- **引话与专名逐字**：模板允许时用 `> ` 引 2–5 条原文关键表态（逐字，不改写）；专名、仪式名、条款名、机构名照原文写全，不要概括成「多个」「若干」「相关」
- **成员称呼**：能对应真实姓名就写姓名；能判断身份就写角色（主持人/考官/甲方/组长/老师…）；两者都不行时**沿用原文的编号称呼**（原文写「发言者2」就写「发言者2」，不要换成别的编号，也不要新编）；同一人在全文只用同一个称呼
- **加粗两头都要管**：每栏至少 1–2 处加粗（关键数字、结论、专名），但**同一行最多 2 处、同一段最多 4 处、同一术语只加粗首次出现**——不要整句加粗、不要每个数字/名词都加粗，也不要整栏一处不加粗
- **未决/待澄清栏口径**：只写内容来源里出现过的分歧、质疑、待验证点；「原文没有写 X」这类缺失说明**不算未决问题**（不要写「原文未明确…」）
- **禁止留空栏**：某栏主题在内容来源里**有依据时必须写内容**（哪怕只有一两句），确实无依据才写该栏约定的缺省词（以模板/占位说明为准，未约定时写「未提及」），不要留空、不要只留标题；**禁止写「原文未提及…」这类缺失说明句**——缺内容只写缺省词，正文不解释缺失
- **语音识别错（错字/专名/数字）**：上下文能明确辨识的按公认写法写（如「结盟不对抗」→「不结盟不对抗」、「chat box TTS」→「ChatTTS」）；无法确定的照原文写；**禁止「可能为X」「疑似X」式猜测补全**（药名、金额、机构名尤其不许猜）"""

