"""正文形态与信息量规则（**单点维护**，多条渲染路径共用同一份文本）。

为什么单独成文件（2026-09 全链路审计结论）：同一套"栏内形态"此前在 5 处各写一份，
草稿 prompt 与渲染 prompt 还停留在旧口径（每条以 `**分类标签**：` 开头、
**每栏至少 2 个分类标签**、每条 20–80 字、加粗每条 2–3 处），与装配侧的新口径冲突：

- 「每栏至少 2 个分类标签」直接造成**标签复用**——一条栏目只有 1–2 类内容时只能重复
  同一个标签（实测行20 出现 `- **盖章互动**：` ×4）；
- 固定条目字数会让简单行动项被迫注水，也会把不可拆的法律条款、医疗说明和技术论据截断；
- 旧口径的"每条以标签开头"正是**裸标签段**（连续多行 `**标签**：长句`、无 `- `）的成因。

2026-09 第二批（now.xlsx 实测，总结复盘会）：改进计划/不足事项类条目只有 21–36 字，
且只剩结论（"老板将更多进行组织协调"），丢了"谁提出 / 针对什么问题 / 到什么程度"。
据此把条目定义从"一个事项**或一个判断**"改成"**一个事项的完整交代**"+ 要素清单，
并单列「禁止结论式孤条」——"或一个判断"原本给了写结论式短条的许可。

现在 5 处统一引用 ``BODY_FORMAT_RULES``：
1. ``tools/template_router/_base.py`` —— 装配路径 system prompt
2. ``tools/template_router/_placeholder.py`` —— 装配路径 user 消息
3. ``tools/templates/template_prompt.py`` —— 自由渲染路径 PLACEHOLDER_RULES
4. ``domain/meeting/tasks/minutes/prompts.py`` —— 纪要草稿 prompt（四.6）
5. 同上 —— 纪要渲染 prompt（呈现形态）
"""
from __future__ import annotations

BODY_FORMAT_RULES = """- **分组不并事实**：并列同类事项（多主体、多事项、多步骤、多分项数据、清单类要点）可按同一主题或大类组织，但组内**必须** `- ` 一条一行保留每个原始事项，标签嵌在行首（`- **标签**：内容`），不得把多条压成一句笼统结论；**同一栏连续 3 行以上独占一行的 `**标签**：`（没有 `- `）算形态缺陷**——清单必须分点；`## 名称` 小节之下**必须** `- ` 一条一行（知识、课堂、清单类尤其如此），不得写成连续段落
- **大类分组（两级层级标准）**：栏内并列条目**超过 6 条时必须归组**——每个板块/议题/阶段/主题一行 `## 组名`（或独占一行的 `**大类**：`），**每组 2–5 条**，组内 `- ` 一条一行；归组维度取原文结构（板块、议题、时间段、成员、环节），组名照原文说法；**一组装不下的事实不硬塞——宁可多分组，不要把无关事实混进同一组**；一条下有 ≥2 个并列子事项时用缩进子条 `  - ` 拆开，不得塞进同一句
- **禁止同名重复**：`## X` 小标题之下第一条**不得**再写 `**X**：`（标题已经说了）；`# 栏名` 之下不得把栏名当标签再复述一遍；**同一栏同一个 `**标签**：` 最多出现 1 次**（同类多条用「一个标签 + 缩进子条 `  - `」聚合，不要重复标签凑数）
- **段落上限**：一般叙述单段不超过 **3 句或约 200 字**，超过就拆段或改成 `- ` 分点；**概况/一段话概括类单段不超过 400 字、最多 3 段；总述栏（首栏）只写一段、不超过 400 字**（该栏自己声明了尺寸的以声明为准）；**例外：问答/对话的一轮（`**称呼**：…`）各占一段，再长也不拆段（长答话按要点压缩）**——条与条之间空一行
- **每条写实**：**每条 = 一个事项的完整交代**——主体（谁/哪个部门提出或负责）+ 具体做法或判断依据 + 针对什么问题（承接现象/根因）+ 程度/数字/时限 + 影响或下一步；原文提供哪些要素就写哪些，不得只留「状态 + 名词」或半句碎片。**条目长度以模板显式要求为准**；模板未声明时按事实完整度自然书写：简单且完整的行动项可以短于 30 字，法律条款、医疗说明、技术论据等不可拆事实可以超过 120 字；只有存在自然边界或多个并列事项时才拆成多条/缩进子条，不得为凑长度扩写或删减事实
- **禁止结论式孤条**：只写「账号未变现」「成本控制差」这类结论不算合格——要交代它对应的事实（什么现象、依据的数字、谁的说法）；原文确实只有方向性表述（如「明年开会再讨论」）时照实写，但要写明它针对什么问题，不得退化成口号
- **条数宁多不漏**：原文有几项就保留几项；同类项可以放进同一主题分组，但每项仍独立成条，不得用综合结论替代；一条只放一件事或一个判断，需要细分时用缩进子条 `  - `
- **同一句话不拆多条**：同一议题的碎片（同一次修改的几个小动作、同一事项的并列子项）合并成一条写清，不要一句一条——「修改了参数」「任务已调整」这类同义半句不单独成条
- **状态标记（✅已完成 / 🔄进行中 / ⏸未开始 / ⛔阻塞）**只在模板要求时使用，且只出现在**表格的状态列或任务名后一次**；条目正文不要逐条重复「进行中」，状态之外必须写清进展内容
- **表格栏**：模板明确写「本栏明细由下表承载」「只用下表」「本栏不再另写说明文字」时，表格是唯一正文，禁止另加总述或复述表格；只有模板未禁止表外文字时，才可按模板需要写一句不重复明细的总体判断。空表如何表示严格按模板约定，不用公共规则覆盖
- **引话与专名逐字**：模板允许时用 `> ` 引 2–5 条原文关键表态（逐字，不改写）；专名、仪式名、条款名、机构名照原文写全，不要概括成「多个」「若干」「相关」
- **问答栏只收真问答**：一方以疑问求信息/确认/解释、对方作出回应，且两者在原文中相邻（同一提问人的连续追问合并成一条）；同一人的自问自答与讲解式设问、主持串场、致谢寒暄、点名管理、单纯表态都不算问答。**问句照原文问法**（原文只有间接表述就概括成一个疑问句），**不得写成「XX提问，…？」式引导转述**。每轮问答是一个记录单元，问、答各占一段；**答话只写回应要点并保持单段，不拆段、不使用列表**。模板未指定上限时，答话超过约 300 字压到 300 字以内；模板显式指定 400 字等上限时以模板为准。**压缩只删例子与铺垫**：数字、条件、限定语（力争/原则上）与发言主体照原文，不得改写、不得把限定语概括掉；原文没有正式问答就写「未提及」，不要硬凑
- **成员称呼**：统一按 **姓名 > 原文明确角色 > 原始编号 > 无主语表达** 回退。原文任何位置出现过该人的姓名就用姓名——哪怕别处只写了角色（「主持人」「发言人」「记者」），已知姓名时不得退回角色；首次可带机构/职务，其后统一简称。原文确实没有姓名才用角色；角色也没有时沿用原文编号（原文写「发言者2」就写「发言者2」，不要换号或新编）；连编号也无法区分时使用无主语句式。对不上是不是同一个人就照原文写（宁可写角色或编号），不得张冠李戴、不得推断或编造姓名；同一人在全文只用一个称呼。**问答/对话中使用的姓名必须有支撑**——在问答段之外的原文里出现过（开场介绍、名单、正文提及），或直接出现在称呼行/相邻句；没有支撑的一律按上述顺序回退。原文出现同音/近音变体（如 晓楠/肖楠/小楠）时取全场主流写法、全篇统一，不两种混用
- **按需加粗**：只突出模板要求的关键结论、原文明确认定的异常值、高风险项、关键时限或必须注意的信息，**不设每栏最低数量**；普通专名、一般数字和常规事实不为装饰而加粗，庭审、合同、医疗等正式记录没有需强调内容时可以整栏不加粗。需要强调时同一行最多 2 处、同一段最多 4 处、同一术语只加粗首次出现；**例外：问答/对话的称呼行按模板要求每轮加粗**，这是对话结构而非内容强调
- **未决/待澄清栏口径**：只写内容来源里出现过的分歧、质疑、待验证点；「原文没有写 X」这类缺失说明**不算未决问题**（不要写「原文未明确…」）
- **禁止留空栏**：某栏主题在内容来源里**有依据时必须写内容**（哪怕只有一两句），确实无依据才写该栏约定的缺省词（以模板/占位说明为准，未约定时写「未提及」），不要留空、不要只留标题；**禁止写「原文未提及…」这类缺失说明句**——缺内容只写缺省词，正文不解释缺失
- **语音识别错（错字/专名/数字）**：上下文能明确辨识的按公认写法写（如「结盟不对抗」→「不结盟不对抗」、「chat box TTS」→「ChatTTS」）；无法确定的照原文写；**禁止「可能为X」「疑似X」式猜测补全**（药名、金额、机构名尤其不许猜）。**人名另加三条**：① 同音/近音变体（晓楠/肖楠/小楠）取全场主流写法、全篇统一；② 外文/音译人名没把握写全就用职务或角色称呼（「会议主席」「主讲人」），不硬凑音译字；③ **禁止造名**——不得把对称联想的名（肖楠↔张楠）、地名/机构名、或「某总」式简称补成全名"""

